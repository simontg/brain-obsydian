#!/usr/bin/env python3
"""wiki_index.py - BM25 index (SQLite FTS5) of a directory of notes; builds INDEX-AUTO.txt.

Usage: wiki_index.py {build,search,export} [query] [--root DIR] [--db FILE] [--out FILE]
build  reads *.txt / *.md under --root (recursive) and rebuilds --db from scratch;
search runs a BM25 query on --db; export writes INDEX-AUTO.txt from --db.
Logic and output format are those of the rclone version; only the source differs
(directory instead of rclone). BOM and CRLF are tolerated, note files are never modified.
Python 3 stdlib only.
"""
import argparse, collections, datetime, re, sqlite3, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wiki_graph import clean, modified

DEFAULT_ROOT = "wiki"
DEFAULT_DB = "index.db"
DEFAULT_OUT = "INDEX-AUTO.txt"
AUTO_NAME = "INDEX-AUTO.txt"
STOP = set("oraz który która które jest nie się dla jako przez przy lub albo także tego tych jego jej ich ten ta to że czy ale tylko jeśli gdy the and for with that this from are not you your will can has have was were been into only when what which".split())


def connect(db):
    Path(db).parent.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(db)
    c.execute("create table if not exists files(path text primary key, modtime text)")
    c.execute("create virtual table if not exists chunks using fts5("
              "path unindexed, title, body, tokenize='unicode61 remove_diacritics 2')")
    return c

def chunk(text, size=800):
    out, cur = [], ""
    for para in re.split(r"\n\s*\n", text):
        para = para.strip()
        if not para:
            continue
        if cur and len(cur) + len(para) > size:
            out.append(cur)
            cur = para
        else:
            cur = (cur + "\n" + para) if cur else para
    if cur:
        out.append(cur)
    return out


def list_notes(root):
    """(posix path relative to root, file) of .txt/.md notes; skips _stary-*, dot dirs, INDEX-AUTO.txt."""
    root = Path(root)
    return [(f.relative_to(root).as_posix(), f) for f in sorted(root.rglob("*"))
            if f.is_file() and f.suffix.lower() in (".txt", ".md") and f.name != AUTO_NAME
            and not any(x.startswith(("_stary-", ".")) for x in f.relative_to(root).parts)]

def build(root, db):
    notes = list_notes(root)
    c = connect(db)
    c.execute("delete from files")
    c.execute("delete from chunks")
    for p, f in notes:
        text = clean(f.read_bytes().decode("utf-8-sig", "replace"))
        first = next((re.sub(r"^[#\s]+", "", l).strip() for l in text.splitlines()
                      if re.search(r"\w{3}", l)), "")
        title = first[:120] if first else p.rsplit("/", 1)[-1]
        for ch in chunk(text):
            c.execute("insert into chunks values(?,?,?)", (p, title, ch))
        c.execute("insert into files values(?,?)", (p, modified(f)))
    c.commit()
    print(f"plikow: {len(notes)}")

def search(db, q, top):
    words = re.findall(r"\w+", q)
    if not words:
        sys.exit("puste zapytanie")
    expr = " OR ".join('"%s"*' % w for w in words)
    c = connect(db)
    rows = c.execute(
        "select path, title, snippet(chunks, 2, '[', ']', ' ... ', 12), bm25(chunks) "
        "from chunks where chunks match ? order by bm25(chunks) limit ?",
        (expr, top * 3)).fetchall()
    seen = set()
    for p, t, s, score in rows:
        if p in seen:
            continue
        seen.add(p)
        print(f"{score:.2f} | {p} | {s.replace(chr(10), ' ')}")
        if len(seen) >= top:
            break
    if not seen:
        print("brak wynikow")

def export(root, db, out, stale_days):
    c = connect(db)
    files = c.execute("select path, modtime from files order by path").fetchall()
    texts = collections.defaultdict(str)
    titles = {}
    for p, t, b in c.execute("select path, title, body from chunks"):
        texts[p] += b + "\n"
        titles[p] = t
    low = {p: t.lower() for p, t in texts.items()}
    now = datetime.datetime.now(datetime.timezone.utc)
    lines = [f"INDEX-AUTO | generated-at: {now.strftime('%Y-%m-%dT%H:%M:%SZ')} | root: {root} | files: {len(files)}",
             "Derived data generated by a script. Notes win on any conflict. Do not edit.", ""]
    back = collections.defaultdict(list)
    outl = collections.defaultdict(list)
    for p in texts:
        t = titles[p].lower()
        if len(t) < 6:
            continue
        for q in texts:
            if q != p and t in low[q]:
                back[p].append(q)
                outl[q].append(p)
    orphans, stale = [], []
    for p, mt in files:
        words = [w for w in re.findall(r"\w{4,}", low.get(p, "")) if w not in STOP and not w.isdigit()]
        kw = ", ".join(w for w, _ in collections.Counter(words).most_common(8))
        lines.append(f"{p} | {titles.get(p, '')[:80]} | modified {mt[:10]} | {len(texts.get(p, ''))} chars")
        lines.append(f"   keywords: {kw}")
        lines.append(f"   linked-from: {len(back[p])}" + (": " + "; ".join(back[p][:5]) if back[p] else ""))
        if not back[p] and not outl[p]:
            orphans.append(p)
        try:
            age = (now - datetime.datetime.fromisoformat(mt.replace("Z", "+00:00"))).days
        except Exception:
            age = 0
        if age > stale_days:
            stale.append(f"{p} ({age} d)")
    lines += ["", f"ORPHANS ({len(orphans)}): " + "; ".join(orphans),
              f"STALE >{stale_days} d ({len(stale)}): " + "; ".join(stale)]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("zapisano", out, "-", len(lines), "linii")

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["build", "search", "export"])
    ap.add_argument("query", nargs="?", default="")
    ap.add_argument("--root", default=DEFAULT_ROOT)
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--top", type=int, default=5)
    ap.add_argument("--stale-days", type=int, default=30)
    a = ap.parse_args()
    if a.cmd == "build":
        build(a.root, a.db)
    elif a.cmd == "search":
        search(a.db, a.query, a.top)
    else:
        export(a.root, a.db, a.out, a.stale_days)
