"""Synthetic check for tools/wiki_index.py. Run: python3 tools/tests/test_wiki_index.py
All titles and contents are made up; no real notes are used."""
import contextlib, hashlib, io, os, re, subprocess, sys, tempfile, time, unittest
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLS))
import wiki_index

BOM = b"\xef\xbb\xbf"
NOTES = {  # relative path -> (text, bom+crlf)
    "Alpha note.txt": ("Alpha note\nType: topic\n\nThe heron wades in the shallows.\n\nSecond paragraph about cormorants.", True),
    "Beta note.txt": ("# Beta note\nType: topic\n\nMentions the Alpha note and a zażółć gęślą jaźń phrase.", True),
    "Lonely.txt": ("Lonely\nType: topic\n\nNothing links here and it links nowhere. Unique token: quokka. Źródło danych. Ktoś lubił herbatę.", False),
    "HOT.txt": ("HOT (state on 2026-01-01, 06:50)\nType: meta\n\nRouter note about herons.", True),
    "sub/Gamma.md": ("Gamma markdown\n\nA nested note about cormorants and unrelated text. Zrodlo bez ogonkow.", False),
    "_stary-old/Skipped.txt": ("Skipped\n\nXylophone must never be indexed.", False),
    ".hidden/Skipped2.txt": ("Skipped2\n\nXylophone must never be indexed either.", False),
    "INDEX-AUTO.txt": ("INDEX-AUTO\n\nXylophone derived file, must be skipped.", False),
    "data.json": ("{\"xylophone\": 1}", False),
}


def write_wiki(d):
    for rel, (text, bom_crlf) in NOTES.items():
        f = d / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(BOM + text.replace("\n", "\r\n").encode("utf-8") if bom_crlf else text.encode("utf-8"))


def digest(d):
    return {str(p.relative_to(d)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(d.rglob("*")) if p.is_file()}


def search(db, query):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        wiki_index.search(db, query, 5)
    return [l.split(" | ")[1] for l in buf.getvalue().split("\n") if l.count(" | ") >= 2], buf.getvalue()


class WikiIndex(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name) / "wiki"
        self.root.mkdir()
        write_wiki(self.root)
        self.before = digest(self.root)
        self.db = str(Path(self._tmp.name) / "out" / "index.db")  # parent dir must be created
        self.out = Path(self._tmp.name) / "INDEX-AUTO.txt"
        with contextlib.redirect_stdout(io.StringIO()):
            wiki_index.build(self.root, self.db)

    def tearDown(self):
        self._tmp.cleanup()

    def export(self):
        with contextlib.redirect_stdout(io.StringIO()):
            wiki_index.export(str(self.root), self.db, str(self.out), 30)
        return self.out.read_text(encoding="utf-8")

    def test_file_selection(self):
        files = [l.split(" | ")[0] for l in self.export().split("\n") if re.search(r" \| modified \d{4}-", l)]
        self.assertEqual(files, ["Alpha note.txt", "Beta note.txt", "HOT.txt", "Lonely.txt", "sub/Gamma.md"])
        self.assertEqual(search(self.db, "xylophone")[0], [])  # skipped dirs/files never indexed
        self.assertEqual(digest(self.root), self.before)  # note files untouched

    def test_bom_crlf_and_titles(self):
        txt = self.export()
        self.assertIn("Alpha note.txt | Alpha note | modified ", txt)
        self.assertIn("Beta note.txt | Beta note | modified ", txt)  # leading '#' stripped
        self.assertIn("HOT.txt | HOT (state on 2026-01-01, 06:50) | modified ", txt)  # title = first line
        self.assertNotIn("\r", txt)
        self.assertNotIn("\ufeff", txt)

    def test_search(self):
        self.assertEqual(search(self.db, "quokka")[0][0], "Lonely.txt")
        self.assertIn("Beta note.txt", search(self.db, "jazn")[0])  # diacritics folded (not l-stroke, as in the rclone version)
        self.assertEqual(search(self.db, "nonexistentword")[1].strip(), "brak wynikow")
        for query in ("zrodlo", "źródło", "ZRODLO", "zródlo"):  # l and ł are one letter
            self.assertCountEqual(search(self.db, query)[0], ["Lonely.txt", "sub/Gamma.md"], query)
        self.assertEqual(search(self.db, "lubil")[0], ["Lonely.txt"])  # mixed l/ł word
        self.assertEqual(search(self.db, "lłlłlłlł")[1].strip(), "brak wynikow")  # >cap letters: no crash
        with self.assertRaises(SystemExit):
            search(self.db, "   ")

    def test_export_format(self):
        lines = self.export().split("\n")
        self.assertRegex(lines[0], r"^INDEX-AUTO \| generated-at: \d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ \| root: .*wiki \| files: 5$")
        self.assertEqual(lines[1], "Derived data generated by a script. Notes win on any conflict. Do not edit.")
        self.assertIn("   linked-from: 1: Beta note.txt", lines)  # Alpha note: title appears in Beta's text
        self.assertTrue(any(l.startswith("   keywords: ") for l in lines))
        self.assertRegex(lines[-3], r"^ORPHANS \(\d+\): ")
        self.assertIn("Lonely.txt", lines[-3])  # no links in or out
        self.assertNotIn("Alpha note.txt", lines[-3])

    def test_stale(self):
        old = time.time() - 90 * 86400
        os.utime(self.root / "Lonely.txt", (old, old))
        with contextlib.redirect_stdout(io.StringIO()):
            wiki_index.build(self.root, self.db)
        stale = self.export().split("\n")[-2]
        self.assertRegex(stale, r"^STALE >30 d \(1\): Lonely\.txt \(9\d d\)$")

    def test_rebuild_is_clean_and_deterministic(self):
        first = self.export().split("\n", 1)[1]
        (self.root / "Lonely.txt").unlink()
        (self.root / "New.txt").write_text("New\n\nFresh content.", encoding="utf-8")
        with contextlib.redirect_stdout(io.StringIO()):
            wiki_index.build(self.root, self.db)
        self.assertEqual(search(self.db, "quokka")[0], [])  # removed note is gone
        self.assertIn("New.txt", self.export())
        (self.root / "Lonely.txt").write_bytes(BOM + NOTES["Lonely.txt"][0].encode("utf-8") if NOTES["Lonely.txt"][1] else NOTES["Lonely.txt"][0].encode("utf-8"))
        (self.root / "New.txt").unlink()
        with contextlib.redirect_stdout(io.StringIO()):
            wiki_index.build(self.root, self.db)
        self.assertEqual(self.export().split("\n", 1)[1].split("modified")[0], first.split("modified")[0])

    def test_cli(self):
        out = Path(self._tmp.name) / "cli.txt"
        base = [sys.executable, "-I", str(TOOLS / "wiki_index.py")]
        db = str(Path(self._tmp.name) / "cli.db")
        subprocess.run(base + ["build", "--root", str(self.root), "--db", db], check=True, capture_output=True)
        subprocess.run(base + ["export", "--root", str(self.root), "--db", db, "--out", str(out)], check=True, capture_output=True)
        self.assertIn("files: 5", out.read_text(encoding="utf-8").split("\n")[0])
        found = subprocess.run(base + ["search", "quokka", "--db", db], check=True, capture_output=True, text=True).stdout
        self.assertIn("Lonely.txt", found)


if __name__ == "__main__":
    unittest.main()
